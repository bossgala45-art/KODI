/** Convertit une question d'examen pour le moteur de quiz, avec ses sources. */
export function toQuizQuestion(question: ExamQuestion): QuizQuestion {
  return {
    id: question.id,
    prompt: question.prompt,
    choices: question.choices,
    correct: question.correct,
    explanation: question.explanation,
    sources: question.sources.map((id) => {
      const source = SOURCES[id];
      return {
        label: `${source.publisher.split(" (")[0]} — « ${source.title} », consulté le ${formatConsultedAt(source.consultedAt)}`,
        url: source.url,
      };
    }),
  };
}

export const EXAM_QUIZ_BANK: readonly QuizQuestion[] = EXAM_QUESTIONS.map(toQuizQuestion);
